export type WindowThemeName = keyof typeof WINDOW_THEMES;

// Accent RGB values for dark mode tinted bodies
const ACCENT_RGB: Partial<Record<WindowThemeName, string>> = {
  blue: '102, 126, 234',
  purple: '168, 85, 247',
  green: '16, 185, 129',
  orange: '249, 115, 22',
  red: '239, 68, 68',
  cyan: '6, 182, 212',
  pink: '236, 72, 153',
  yellow: '234, 179, 8',
  indigo: '99, 102, 241',
  teal: '20, 184, 166',
  slate: '100, 116, 139',
};

export function getTheme(themeName: WindowThemeName, isDark: boolean): WindowTheme {
  const base = WINDOW_THEMES[themeName];

  // Window body lightness must ALWAYS follow the OS light/dark mode: app
  // content inside styles itself with Tailwind `dark:` classes driven by
  // html.dark, so a dark body in light mode (or vice versa) makes that
  // content unreadable.
  if (themeName === 'dark') {
    if (isDark) return base;
    // Light mode: keep the dark-accent header but give the body a light
    // background so light-mode content stays readable.
    return {
      ...base,
      bodyBg: 'rgba(249, 250, 251, 0.95)',
      bodyText: '#1f2937',
      borderColor: 'rgba(107, 114, 128, 0.45)',
      shadowColor: 'rgba(0, 0, 0, 0.18)',
    };
  }

  // Glass theme: keep the frosted look but guarantee contrast — semi-opaque
  // white with dark text in light mode, semi-opaque near-black with light
  // text in dark mode (pure 5% white was illegible over light wallpapers).
  if (themeName === 'glass') {
    if (!isDark) {
      return {
        ...base,
        headerBg: 'rgba(255, 255, 255, 0.5)',
        headerText: '#1f2937',
        bodyBg: 'rgba(255, 255, 255, 0.6)',
        bodyText: '#1f2937',
        borderColor: 'rgba(0, 0, 0, 0.1)',
        accentColor: '#0078D4',
      };
    }
    return {
      ...base,
      headerBg: 'rgba(17, 24, 39, 0.45)',
      bodyBg: 'rgba(17, 24, 39, 0.55)',
    };
  }

  if (!isDark) return base;

  // 'default' in dark mode becomes the dark theme
  if (themeName === 'default') return WINDOW_THEMES.dark;

  // 'minimal' gets fully dark
  if (themeName === 'minimal') {
    return {
      headerBg: '#1f2937',
      headerText: '#f9fafb',
      headerBorder: '#374151',
      bodyBg: '#111827',
      bodyText: '#f9fafb',
      accentColor: '#9ca3af',
      glassEffect: false,
      borderColor: '#374151',
      shadowColor: 'rgba(0, 0, 0, 0.3)',
    };
  }

  // Colored themes: keep header, darken body with solid dark + subtle accent tint
  const rgb = ACCENT_RGB[themeName];
  const tintedDarkBody = rgb
    ? `linear-gradient(135deg, rgba(17, 24, 39, 0.97) 0%, rgba(${rgb}, 0.15) 100%)`
    : 'rgba(17, 24, 39, 0.97)';

  return {
    ...base,
    bodyBg: tintedDarkBody,
    bodyText: '#f9fafb',
    headerBorder: base.headerBorder?.replace(/0\.\d+\)$/, '0.6)'),
    borderColor: base.borderColor?.replace(/0\.\d+\)$/, '0.5)'),
    shadowColor: base.shadowColor?.replace(/0\.\d+\)$/, '0.4)'),
  };
}

export function resolveThemeName(theme: WindowTheme | undefined): WindowThemeName {
  if (!theme) return 'default';
  for (const [name, t] of Object.entries(WINDOW_THEMES)) {
    if (t === theme) return name as WindowThemeName;
  }
  return 'default';
}

